"""Bakes PAPERMARCH's font into a signed-distance-field atlas (TECH_SPEC 5.7).

    python -I -B tools/bake_font.py [--font assets/font/Roboto-Black.ttf] [--sample captures/p1/font_sample.png]

Renders every glyph the game shows at 96 px, rounds its corners (an opening: erode, then dilate, by a few pixels),
builds a distance field with a 14 px spread, halves it into ~48 px cells packed in one R8 atlas, and writes
src/gfx/font_atlas.inc and src/gfx/font_metrics.inc (committed, so no build needs Python). Fails if a glyph is missing.
"""
import argparse
import os
import sys

import numpy as np
from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CHARS = "0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ .,:!?'-+%/()×÷"
RENDER = 96        # px per em at render time
SPREAD = 14        # px at render size
ROUND = 4          # corner rounding radius, px at render size
ATLAS_W = 512


def edt(mask, radius):
    """Distance (px) from each pixel to the nearest pixel where mask is False, capped at radius+1 (brute force).
    Pixels outside the image never count as targets."""
    h, w = mask.shape
    big = radius + 1.0
    dist = np.where(mask, big, 0.0)
    pad = int(radius) + 1
    padded = np.pad(mask, pad, constant_values=True)
    for dy in range(-pad, pad + 1):
        for dx in range(-pad, pad + 1):
            d = (dx * dx + dy * dy) ** 0.5
            if d == 0 or d > radius + 1:
                continue
            shifted = padded[pad + dy:pad + dy + h, pad + dx:pad + dx + w]
            hit = mask & ~shifted
            np.minimum(dist, np.where(hit, d, big), out=dist)
    return dist


def glyph_sdf(font, ch):
    pad = SPREAD + ROUND + 4
    bbox = font.getbbox(ch)
    gw, gh = max(1, bbox[2] - bbox[0]), max(1, bbox[3] - bbox[1])
    img = Image.new("L", (gw + 2 * pad, gh + 2 * pad), 0)
    ImageDraw.Draw(img).text((pad - bbox[0], pad - bbox[1]), ch, font=font, fill=255)
    a = np.asarray(img) >= 128
    if ch != " " and not a.any():
        raise SystemExit(f"bake_font: the font has no glyph for {ch!r}")
    if ROUND > 0 and a.any():
        inside = edt(a, ROUND + 1)
        eroded = inside > ROUND
        outside_of_eroded = edt(~eroded, ROUND + 1)
        a = outside_of_eroded <= ROUND  # dilate the eroded shape: convex corners come back rounded
    din = edt(a, SPREAD)       # inside: distance to the edge
    dout = edt(~a, SPREAD)     # outside: distance to the shape
    sd = np.where(a, din - 0.5, -(dout - 0.5))  # px, positive inside
    # Halve: 2x2 average of the distance (in render px), then convert to atlas px.
    h, w = sd.shape
    sd = sd[: h - h % 2, : w - w % 2]
    sd = sd.reshape(sd.shape[0] // 2, 2, sd.shape[1] // 2, 2).mean(axis=(1, 3)) / 2.0
    spread_atlas = SPREAD / 2.0
    val = np.clip(0.5 + sd / (2.0 * spread_atlas), 0.0, 1.0)
    # Offset of the cell's top-left from the pen position (baseline origin), in render px.
    ox, oy = bbox[0] - pad, bbox[1] - pad
    return (val * 255.0 + 0.5).astype(np.uint8), ox, oy


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--font", default=os.path.join(ROOT, "assets", "font", "Roboto-Black.ttf"))
    ap.add_argument("--sample", default=os.path.join(ROOT, "captures", "p1", "font_sample.png"))
    args = ap.parse_args()
    font = ImageFont.truetype(args.font, RENDER)
    ascent, descent = font.getmetrics()

    cells = []
    for ch in CHARS:
        data, ox, oy = glyph_sdf(font, ch)
        adv = font.getlength(ch)
        cells.append((ch, data, ox, oy, adv))
    digit_adv = max(c[4] for c in cells if c[0].isdigit())

    # Shelf packing.
    x = y = shelf = 0
    places = []
    for ch, data, ox, oy, adv in cells:
        h, w = data.shape
        if x + w > ATLAS_W:
            x, y, shelf = 0, y + shelf + 1, 0
        places.append((x, y))
        x += w + 1
        shelf = max(shelf, h)
    atlas_h = y + shelf + 1
    atlas_h = 1 << (atlas_h - 1).bit_length()
    atlas = np.zeros((atlas_h, ATLAS_W), np.uint8)
    for (ch, data, ox, oy, adv), (px, py) in zip(cells, places):
        h, w = data.shape
        atlas[py:py + h, px:px + w] = data

    out_dir = os.path.join(ROOT, "src", "gfx")
    with open(os.path.join(out_dir, "font_atlas.inc"), "w", encoding="ascii") as f:
        f.write("// Generated by tools/bake_font.py - do not edit.\n")
        f.write(f"constexpr int kFontAtlasW = {ATLAS_W}, kFontAtlasH = {atlas_h};\n")
        f.write(f"constexpr float kFontSpread = {SPREAD / 2.0}f;  // atlas px\n")
        f.write("static const unsigned char kFontAtlas[] = {\n")
        flat = atlas.reshape(-1)
        for i in range(0, flat.size, 32):
            f.write(",".join(str(int(v)) for v in flat[i:i + 32]) + ",\n")
        f.write("};\n")
    em = RENDER / 2.0  # atlas px per em
    with open(os.path.join(out_dir, "font_metrics.inc"), "w", encoding="ascii") as f:
        f.write("// Generated by tools/bake_font.py - do not edit. Units: em (1 = the font size), y down.\n")
        f.write(f"constexpr float kFontAscent = {ascent / RENDER:.5f}f, kFontDescent = {descent / RENDER:.5f}f;\n")
        f.write(f"constexpr float kFontAtlasPxPerEm = {em:.3f}f;\n")
        f.write("// code, atlas x, y, w, h, offset x, offset y (cell's top-left from the pen at the baseline), advance\n")
        f.write("static const FontGlyph kFontGlyphs[] = {\n")
        for (ch, data, ox, oy, adv), (px, py) in zip(cells, places):
            h, w = data.shape
            a = digit_adv if ch.isdigit() else adv
            shift = (digit_adv - adv) / 2.0 if ch.isdigit() else 0.0
            f.write(f"    {{{ord(ch)}, {px}, {py}, {w}, {h}, {(ox + shift) / RENDER:.5f}f, {(oy - ascent) / RENDER:.5f}f, "
                    f"{a / RENDER:.5f}f}},\n")
        f.write("};\n")
    print(f"bake_font: {len(cells)} glyphs, atlas {ATLAS_W}x{atlas_h}")

    # Sample sheet: the atlas, and every string at two sizes rendered from the field (fill + dark stroke).
    os.makedirs(os.path.dirname(args.sample), exist_ok=True)
    samples = ["0123456789", "×2  ×3  ×5  ÷2  ÷3", "LEVEL 12", "2,480", "CLEARED!", "SNUFFED OUT",
               "HOLD AND DRAG", "NEXT  RETRY  RESUME", "FLOOD ×1,000", "SOUND  MUSIC  HAPTICS"]
    sheet = Image.new("RGB", (1200, 1100), (30, 26, 70))
    d = ImageDraw.Draw(sheet)
    glyphs = {c[0]: (c, p) for c, p in zip(cells, places)}
    yy = 20
    for s in samples:
        for size in (44, 88):
            pen = 20.0
            scale = size / em
            canvas = np.zeros((int(size * 1.4), 1200), np.float32)
            fill = np.zeros_like(canvas)
            for ch in s:
                (c, (px, py)) = glyphs[ch]
                _, data, ox, oy, adv = c
                a = digit_adv if ch.isdigit() else adv
                shift = (digit_adv - adv) / 2.0 if ch.isdigit() else 0.0
                h, w = data.shape
                img = Image.fromarray(data).resize((max(1, int(w * scale)), max(1, int(h * scale))), Image.BILINEAR)
                g = np.asarray(img).astype(np.float32) / 255.0
                gx = int(pen + (ox + shift) / RENDER * size)
                gy = int(size * 1.1 + (oy - ascent) / RENDER * size)
                hh, ww = g.shape
                y0, x0 = max(gy, 0), max(gx, 0)
                y1, x1 = min(gy + hh, canvas.shape[0]), min(gx + ww, canvas.shape[1])
                if y1 > y0 and x1 > x0:
                    sub = g[y0 - gy:y1 - gy, x0 - gx:x1 - gx]
                    canvas[y0:y1, x0:x1] = np.maximum(canvas[y0:y1, x0:x1], sub)
                pen += a / RENDER * size
            dist = (canvas - 0.5) * 2.0 * (SPREAD / 2.0) * scale  # px
            fa = np.clip(dist + 0.5, 0, 1)
            sa = np.clip(dist + max(3.0, size * 0.08) + 0.5, 0, 1)
            rgb = np.zeros(canvas.shape + (3,), np.float32)
            bg = np.array([30, 26, 70], np.float32)
            stroke = np.array([22, 14, 52], np.float32)
            white = np.array([255, 255, 255], np.float32)
            rgb[:] = bg
            rgb = rgb * (1 - sa[..., None]) + stroke * sa[..., None]
            rgb = rgb * (1 - fa[..., None]) + white * fa[..., None]
            strip = Image.fromarray(rgb.clip(0, 255).astype(np.uint8))
            sheet.paste(strip, (0, yy))
            yy += strip.size[1]
            if yy > sheet.size[1] - 140:
                break
        if yy > sheet.size[1] - 140:
            break
    atlas_img = Image.fromarray(atlas).convert("RGB")
    atlas_img.thumbnail((380, 380))
    sheet.paste(atlas_img, (sheet.size[0] - atlas_img.size[0] - 10, sheet.size[1] - atlas_img.size[1] - 10))
    sheet.save(args.sample)
    print("bake_font: sample", args.sample)
    return 0


if __name__ == "__main__":
    sys.exit(main())
