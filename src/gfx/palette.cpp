const WorldPalette& worldPalette(int world) { return kWorlds[((world < 1 ? 1 : world) - 1) % kWorldCount]; }
const char* bossName(int world) { return kBosses[((world < 1 ? 1 : world) - 1) % kWorldCount]; }

float luminance(u32 rgb) { return 0.2126f * channel(rgb >> 16) + 0.7152f * channel(rgb >> 8) + 0.0722f * channel(rgb); }

float contrast(u32 a, u32 b) {
    const float la = luminance(a), lb = luminance(b);
    return (la > lb ? la + 0.05f : lb + 0.05f) / (la > lb ? lb + 0.05f : la + 0.05f);
}

float hueOf(u32 rgb) {
    const float r = float((rgb >> 16) & 0xFF) / 255.0f, g = float((rgb >> 8) & 0xFF) / 255.0f, b = float(rgb & 0xFF) / 255.0f;
    const float mx = std::fmax(r, std::fmax(g, b)), mn = std::fmin(r, std::fmin(g, b));
    if (mx - mn < 1e-5f) return 0;
    float h;
    if (mx == r) h = std::fmod((g - b) / (mx - mn), 6.0f);
    else if (mx == g) h = (b - r) / (mx - mn) + 2.0f;
    else h = (r - g) / (mx - mn) + 4.0f;
    h *= 60.0f;
    return h < 0 ? h + 360.0f : h;
}

